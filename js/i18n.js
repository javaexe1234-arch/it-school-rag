const Lang = {
  KEY: 'itschool_lang',
  current: 'ru',
  init() {
    let l = null;
    try { l = localStorage.getItem(Lang.KEY); } catch (e) {}
    if (!l || !I18N[l]) {
      const nav = (navigator.language || 'ru').slice(0, 2);
      l = I18N[nav] ? nav : 'ru';
    }
    Lang.current = l;
  },
  set(l) {
    if (!I18N[l]) return;
    Lang.current = l;
    try { localStorage.setItem(Lang.KEY, l); } catch (e) {}
  },
  t(key) { return (I18N[Lang.current] && I18N[Lang.current][key]) || I18N.ru[key] || key; }
};
Lang.init();
